    applyPriceFilter() {
        const rawMin = this.dom.filterPriceMinInput?.value;
        const rawMax = this.dom.filterPriceMaxInput?.value;
        const parsedMin = rawMin === '' ? null : Number(rawMin);
        const parsedMax = rawMax === '' ? null : Number(rawMax);
        this.minPrice = Number.isFinite(parsedMin) && parsedMin >= 0 ? parsedMin : null;
        this.maxPrice = Number.isFinite(parsedMax) && parsedMax >= 0 ? parsedMax : null;
        if (this.minPrice != null && this.maxPrice != null && this.minPrice > this.maxPrice) {
            this.maxPrice = this.minPrice;
        }
        this.refreshCurrentView();
        this.renderFilterBar();
        this.renderFilterModal();
    },

